/* shadow_view.h — интерфейс представления буфера для чтения (дан готовым).
 *
 * Как и shadow_ring.c, этот слой НЕ зависит от ядра: он превращает
 * измерения в текст и отвечает на главный вопрос драйвера символьного
 * устройства — «сколько байт отдать при этом вызове read()».
 *
 * Именно здесь живёт ошибка, которую в ядре ловят неделями: read()
 * вызывается многократно, с разными count и с растущей позицией, и
 * драйвер, который каждый раз отдаёт всё сначала, работает ровно до
 * первого `head -c 5 /dev/shadow0`.
 */
#ifndef SHADOW_VIEW_H
#define SHADOW_VIEW_H

#include <stddef.h>

#include "shadow_ring.h"

/* Одна запись в текст: "seq=12 t=23.062\n".
 * Возвращает число записанных байт (без завершающего нуля) или -1,
 * если не поместилось. Плавающая точка не используется. */
int shadow_format_line(unsigned long seq, int milli, char *buf, size_t cap);

/* Весь буфер в текст, от самого старого к самому свежему.
 * Возвращает длину или -1, если не поместилось. */
int shadow_render(const struct shadow_ring *r, char *buf, size_t cap);

/* Сколько байт отдать при чтении count байт с позиции pos и что именно.
 * Копирует в dst не больше count байт, начиная с pos.
 * Возвращает число скопированных байт, 0 — конец данных (EOF),
 * -1 — ошибка аргументов. */
int shadow_copy_slice(const char *src, size_t len, size_t pos,
		      char *dst, size_t count);

#endif /* SHADOW_VIEW_H */
