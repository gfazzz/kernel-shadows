#!/usr/bin/env bash
#
# iac_audit.sh — аудит репозитория инфраструктуры (СТАРТЕР)
#
# Пока умеет одно: сказать, сколько файлов отслеживает git. Это, впрочем,
# уже больше, чем делает большинство отчётов о безопасности: число видно.
#
# Правь копию в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md). Восемь разделов,
# каждый — находка одной из серий сезона:
#
#   secrets    значение, похожее на секрет, в отслеживаемом файле  (s04e03)
#   history    запретный файл, побывавший в истории git            (s04e01)
#   gitignore  .gitignore не закрывает секреты — или закрывает
#              пример конфигурации                                 (s04e03)
#   docker     база без точной версии, работа от root, ключ в COPY (s04e05)
#   compose    privileged, docker.sock, порт на всех интерфейсах   (s04e06)
#   ci         незакреплённое действие, «|| true», нет permissions (s04e07)
#   ansible    пароль в инвентаре, root, StrictHostKeyChecking=no  (s04e09)
#   perms      закрытый ключ читается не только владельцем         (s01e15)
#
# Каждая находка печатается строкой с важностью (ВЫСОКАЯ или СРЕДНЯЯ),
# разделом, путём и внятным объяснением. В конце — сколько чего проверено
# и сколько найдено.
#
# Коды возврата: 0 — чисто, 1 — есть находки, 2 — ошибка вызова или
# проверять оказалось нечего. Последнее важно: «находок нет» и «искать
# было негде» снаружи выглядят одинаково.

set -euo pipefail

REPO="."

while [ $# -gt 0 ]; do
    case "$1" in
        --repo) REPO="${2:-}"; shift 2 ;;
        *) shift ;;
    esac
done

git -C "${REPO}" rev-parse --git-dir >/dev/null 2>&1 \
    || { echo "не репозиторий: ${REPO}" >&2; exit 2; }

n=$(git -C "${REPO}" ls-files | grep -c . || true)
echo "отслеживаемых файлов: ${n}"
exit 0
