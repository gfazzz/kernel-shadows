#!/usr/bin/env bash
#
# gpio_ctl.sh — управление ножками GPIO через sysfs (СТАРТЕР, s06e02).
#
# Ядро выставляет GPIO наружу обычными файлами. Всё управление — это
# запись в файлы и чтение из них:
#
#   echo 17  > $ROOT/export             занять ножку -> появится gpio17/
#   echo out > $ROOT/gpio17/direction   сделать её выходом
#   echo 1   > $ROOT/gpio17/value       подать высокий уровень
#   cat        $ROOT/gpio17/value       прочитать уровень
#   echo 17  > $ROOT/unexport           освободить
#
# Задача — обернуть это в скрипт, который не даст сжечь плату:
# проверит, что ножка существует, что она не занята другой периферией,
# что она экспортирована и что направление позволяет операцию.
#
# Занятость ножек НЕ зашивать в код: она читается из карты (--map).
# У другой платы карта другая, а скрипт должен остаться тем же.
#
# Коды возврата (соблюдать точно, тест их проверяет):
#   0 — успех
#   1 — ошибка использования (аргументы, неизвестная команда, плохое значение)
#   2 — нет sysfs GPIO (каталога или файла export)
#   3 — такого пина нет на гребёнке
#   4 — пин не экспортирован или направление не позволяет операцию
#   5 — пин занят другой периферией

set -uo pipefail

