#!/usr/bin/env bash
#
# prepush_check.sh — что проверить до `git push` (СТАРТЕР)
#
# Пока умеет одно: сказать, на какой ветке вы находитесь. Это уже больше,
# чем делают многие, — и всё же недостаточно, чтобы пароль не уехал
# в общий репозиторий во второй раз.
#
# Правь этот файл в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md):
#   отказ при попытке отправить прямо в основную ветку; поиск секретов
#   в тех коммитах, которые уйдут; запрет на файлы, которых в репозитории
#   быть не должно; предел размера; конфликтные маркеры. Каждая находка —
#   с указанием коммита и файла, и ненулевой код возврата.

set -euo pipefail

REPO="."

while [ $# -gt 0 ]; do
    case "$1" in
        --repo) REPO="$2"; shift 2 ;;
        *) echo "неизвестный аргумент: $1" >&2; exit 2 ;;
    esac
done

branch=$(git -C "$REPO" rev-parse --abbrev-ref HEAD)
echo "текущая ветка: $branch"
exit 0
