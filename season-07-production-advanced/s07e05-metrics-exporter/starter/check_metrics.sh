#!/usr/bin/env bash
#
# check_metrics.sh — аудит выдачи /metrics (СТАРТЕР)
#
# ВЫЗОВ
#   check_metrics.sh <файл-выдачи> <файл-соглашений>
#
# ВХОД
#   выдача      формат экспозиции Prometheus: служебные строки «# HELP имя …»
#               и «# TYPE имя тип», дальше «имя{метки} значение»
#   соглашения  data/limits.txt: max_label_values, base_unit, bad_unit
#
#   Рядом с каждой выдачей лежит answers.txt — что нашёл promtool.
#   Открывать его нельзя, тест проверяет это поиском по тексту скрипта.
#
# ВЫВОД
#   ISSUE <код> <семейство> <пояснение>     по строке на нарушение
#   SUMMARY <n> issues, <m> metrics, <k> series
#
#   Коды: no-help, no-type, unit, counter-suffix, histogram, cardinality.
#   Семейство — имя метрики без суффиксов _bucket, _sum, _count.
#
# КОД ВОЗВРАТА
#   0 — нарушений нет   1 — есть   2 — вход не разобрать
#
# ШЕСТЬ ПРАВИЛ
#   no-help         у семейства нет строки HELP
#   no-type         у семейства нет строки TYPE
#   unit            имя оканчивается единицей из списка bad_unit
#   counter-suffix  тип counter, а имя не оканчивается на _total
#   histogram       нет корзины le="+Inf", нет _sum/_count, либо +Inf ≠ _count
#   cardinality     у какой-то метки больше max_label_values разных значений
#                   (метки le и quantile не считаются: их набор задан
#                    самим определением гистограммы и сводки)
#
# ПОДСКАЗКИ К РЕШЕНИЮ (не к коду)
#   - Пороги и списки берутся из файла соглашений. Зашитое в скрипт число
#     тест поймает: он поднимет порог и проверит, что вывод изменился.
#   - «Разных значений метки» — это разные пары ключ="значение", а не
#     разные ряды: у одной метрики может быть несколько меток сразу.
#   - Порядок вывода должен быть устойчивым между прогонами.

