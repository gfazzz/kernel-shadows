#!/usr/bin/env bash
#
# whereami.sh — s01e01 «Terminal Awakening» (СТАРТЕР)
#
# Задача: инструмент ориентации. Скрипт должен ответить на вопрос
# «где я сейчас в дереве файловой системы?».
#
# Как проходить:
#   1. Скопируй файл в рабочую папку:  cp starter/whereami.sh artifacts/whereami.sh
#   2. Замени TODO своим кодом.
#   3. Проверь:  bash tests/test.sh
#
# Требования среды: любой bash, без root, без сети. Критерии — в mission.md.

set -euo pipefail

# TODO 1: получи текущий абсолютный путь (подсказка: команда из 3 букв)
#         и сохрани его в переменную here.
here=$(pwd) # <-- замени на вызов нужной команды

# TODO 2: выведи текущую директорию и домашнюю директорию ($HOME).
#         Формат вывода — на твой вкус, но путь из TODO 1 должен быть напечатан.
echo "Текущая директория (pwd):   ${here}"
echo "Домашняя директория (HOME): ${HOME}"

# TODO 3: определи, находишься ли ты в корне "/", и напечатай понятный статус.
#         if [ "${here}" = "/" ]; then ... else ... fi
if [ "${here}" = "/" ]; then
    echo "Вы находитесь в корневой директории."
else
    echo "Вы находитесь не в корневой директории."
fi
# TODO 4 (бонус): сравни here с $HOME и сообщи, дома ли ты.
if [ "${here}" = "${HOME}" ]; then
    echo "Вы находитесь в домашней директории."
else
    echo "Вы находитесь не в домашней директории."
fi
