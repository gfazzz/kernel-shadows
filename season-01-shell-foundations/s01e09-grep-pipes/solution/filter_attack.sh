#!/usr/bin/env bash
#
# filter_attack.sh — s01e09 «Фильтрация логов атаки»
# Эталон (открывать ПОСЛЕ своей попытки).
#
# Концепт: grep (фильтр строк) + pipe (конвейер команд).
# Type A — Bash Automation (обёртка над grep-конвейером).
#
# Требования среды: bash + grep, без root, без сети. Работает на фикстуре-логе.
#
# Идея: во время атаки «нормальные» ответы — HTTP 200. Всё остальное
# (403/401/404/500...) — подозрительно. Выделяем не-200 и считаем.

set -uo pipefail

log="${1:?Использование: filter_attack.sh ACCESS_LOG}"
[ -f "${log}" ] || { echo "Файл не найден: ${log}" >&2; exit 1; }

echo "=== Подозрительные запросы (HTTP-статус не 200) ==="
grep -vE ' 200 ' "${log}"

echo "---"
# Конвейер: тот же фильтр, но результат считаем (grep | wc).
total=$(grep -vE ' 200 ' "${log}" | wc -l)
echo "Подозрительных запросов: ${total}"
