#!/usr/bin/env bash
#
# restore_check.sh — проверка бэкапа (СТАРТЕР)
#
# Так это выглядело у Дмитрия. Скрипт смотрит, что каталог существует
# и что в нём что-то есть. На вопрос «восстановится ли из него система»
# он не отвечает — и никогда не отвечал.
#
# Правь этот файл в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md):
#   восстановление во временный каталог, сверка каждого файла с манифестом,
#   поимённый список испорченных, пропавших и лишних, машиночитаемый отчёт,
#   ненулевой код возврата при любом расхождении — и ни одного изменения
#   в самом бэкапе.

BACKUP="/srv/backup/latest"

if [ -d "$BACKUP" ]; then
    n=$(ls "$BACKUP" | wc -l)
    echo "бэкап на месте, файлов: $n"
    exit 0
else
    echo "бэкапа нет"
    exit 1
fi
