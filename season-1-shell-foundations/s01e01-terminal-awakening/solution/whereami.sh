#!/usr/bin/env bash
#
# whereami.sh — s01e01 «Terminal Awakening»
# Эталонное решение (открывать ПОСЛЕ своей попытки).
#
# Концепт серии: pwd — где я в дереве файловой системы.
# Type A — Bash Automation: маленький скрипт-обёртка, чтобы ориентацию
# можно было повторять одной командой (а не набирать pwd/echo каждый раз).
#
# Требования среды: любой bash, без root, без сети. Работает на Linux/macOS/WSL.

set -euo pipefail

# 1) Где я сейчас — абсолютный путь от корня "/".
here="$(pwd)"

# 2) Где мой "дом" — стартовая директория пользователя.
home="${HOME:-неизвестно}"

echo "Текущая директория (pwd):   ${here}"
echo "Домашняя директория (HOME): ${home}"

# 3) Корень или нет? На чужом сервере это первое, что важно понять.
if [ "${here}" = "/" ]; then
    echo "Статус: ты в КОРНЕ файловой системы (/). Это 'подвал здания' — будь осторожен."
else
    echo "Статус: путь выше — абсолютный (начинается с /). Ты не в корне."
fi

# 4) Ты дома?
if [ "${here}" = "${home}" ]; then
    echo "Дом: да, ты в своей домашней директории."
else
    echo "Дом: нет, ты вне \$HOME. Чтобы вернуться домой — команда 'cd' (следующая серия)."
fi
