#!/usr/bin/env bash
#
# setup_workspace.sh — подготовка рабочего каталога операции (СТАРТЕР)
#
# Пока он умеет одно: создать каталоги. Про права в нём не сказано ничего,
# и это значит, что права будут какие получатся — те, что оставит umask.
#
# Правь этот файл в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md):
#   четыре каталога с заданными правами; файлы внутри тоже приведены
#   к нужным правам; повторный запуск ничего не ломает, а ЧИНИТ то,
#   что кто-то испортил; ни одной команды с sudo.

set -euo pipefail

ROOT=""

while [ $# -gt 0 ]; do
    case "$1" in
        --root) ROOT="$2"; shift 2 ;;
        *) echo "неизвестный аргумент: $1" >&2; exit 2 ;;
    esac
done

mkdir -p "$ROOT/scripts"
mkdir -p "$ROOT/secrets"
mkdir -p "$ROOT/reports"
mkdir -p "$ROOT/logs"

echo "каталоги созданы"
