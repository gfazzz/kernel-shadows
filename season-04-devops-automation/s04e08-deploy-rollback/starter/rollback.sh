#!/usr/bin/env bash
#
# rollback.sh — вернуть в бой предыдущую рабочую версию (СТАРТЕР)
#
# Пока умеет одно: сказать, что сейчас в бою. Это ровно то, что успевает
# сделать человек за первую минуту инцидента, — и ровно на минуту меньше,
# чем нужно.
#
# Правь копию в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md):
#
#   Журнал выкатов — строки вида
#       время  версия  состояние  миграция  [комментарий]
#   Состояние: healthy | failed. Одна и та же версия встречается несколько
#   раз; значение имеет последняя запись о ней.
#
#   1. Цель отката — последняя версия, чьё ПОСЛЕДНЕЕ состояние healthy.
#      Строка перед текущей не годится: она может быть failed.
#   2. Если после цели применялись миграции схемы — отказ (код 3):
#      откат кода их не отменяет. Через --force — можно.
#   3. Выкат — точным тегом версии, по ssh, на хост из --host.
#   4. После выката — проверка готовности. Не ответила — код возврата 1.
#   5. Журнал дописывается: снятая версия — failed, восстановленная —
#      healthy. Иначе следующий откат вернёт в бой то же самое.
#   6. --dry-run печатает план и не меняет ничего.

set -euo pipefail

JOURNAL=""; HOST=""; IMAGE=""

while [ $# -gt 0 ]; do
    case "$1" in
        --journal) JOURNAL="${2:-}"; shift 2 ;;
        --host)    HOST="${2:-}";    shift 2 ;;
        --image)   IMAGE="${2:-}";   shift 2 ;;
        *) shift ;;
    esac
done

[ -f "${JOURNAL}" ] || { echo "нет журнала выкатов: ${JOURNAL}" >&2; exit 2; }

current=$(grep -vE '^[[:space:]]*(#|$)' "${JOURNAL}" | tail -1 | awk '{print $2}')
echo "сейчас в бою: ${current}"
exit 0
