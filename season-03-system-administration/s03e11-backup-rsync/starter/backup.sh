#!/usr/bin/env bash
#
# backup.sh — резервное копирование (СТАРТЕР)
#
# Так это выглядело у Дмитрия: каталог копируется целиком, каждый раз
# заново. Работает — пока каталог небольшой и пока никто не спрашивает,
# из какого именно снимка восстанавливаться.
#
# Правь этот файл в artifacts/, потом проверяй:  bash tests/test.sh
#
# Что должно получиться (подробности — в mission.md):
#   снимок, занимающий место только под изменения; манифест с контрольными
#   суммами; защита от одновременного запуска; список исключений;
#   холостой прогон; ограничение числа хранимых снимков.

SOURCE="/var/log/ops"
DEST="/srv/backup"

DATE=$(date +%F)
cp -r "$SOURCE" "$DEST/$DATE"
echo "бэкап сделан"
