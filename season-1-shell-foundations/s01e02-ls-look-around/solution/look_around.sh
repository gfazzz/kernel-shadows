#!/usr/bin/env bash
#
# look_around.sh — s01e02 «Осмотреться»
# Эталон (открывать ПОСЛЕ своей попытки).
#
# Концепт: ls — увидеть, что вокруг, ВКЛЮЧАЯ скрытые файлы (начинаются с точки).
# Type A — Bash Automation: обёртка над ls, чтобы «включать свет» одной командой.
#
# Требования среды: любой bash + coreutils, без root, без сети.

set -euo pipefail

# Директория для осмотра; по умолчанию — текущая.
target="${1:-.}"

echo "Осматриваю: ${target}"
echo "--- всё содержимое (детали + скрытые), ls -la ---"
ls -la "${target}"

# Скрытые объекты — те, что начинаются с точки (кроме . и ..).
# ls -A показывает всё, кроме . и ..; считаем строки, начинающиеся с точки.
hidden_count="$(ls -A "${target}" 2>/dev/null | grep -c '^\.' || true)"
echo "Скрытых объектов (кроме . и ..): ${hidden_count}"

if [ "${hidden_count}" -gt 0 ]; then
    echo "Скрытое найдено — не полагайся на обычный ls. Атакующие прячут файлы за точкой."
else
    echo "Скрытых файлов нет."
fi
